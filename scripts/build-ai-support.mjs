import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')

export const SOURCE_DOCS = [
  'docs/llm-instructions.md',
  'docs/product.md',
  'docs/getting-started.md',
  'docs/user-guide.md',
  'docs/configuration.md',
  'docs/reference.md',
  'docs/troubleshooting.md',
  'docs/FAQ.md',
  'docs/architecture.md',
  'docs/development.md',
  'docs/roadmap.md',
]

function read(rel) {
  return fs.readFileSync(path.join(root, rel), 'utf8').replace(/\r\n/g, '\n')
}

function titleOf(markdown) {
  const line = markdown.split('\n').find((l) => l.startsWith('# '))
  return line ? line.slice(2).trim() : 'Section'
}

function faqQuestions(markdown) {
  return markdown
    .split('\n')
    .filter((l) => l.startsWith('### '))
    .map((l) => l.slice(4).trim())
}

function symptomRows(markdown) {
  const rows = []
  for (const line of markdown.split('\n')) {
    if (!line.startsWith('|') || line.includes('Symptom') || line.includes('---')) continue
    const cells = line.split('|').map((c) => c.trim()).filter(Boolean)
    if (cells.length >= 2 && !cells[0].startsWith('Symptom')) rows.push(cells[0])
  }
  return rows
}

export function buildAiSupport() {
  const pkg = JSON.parse(read('package.json'))
  const version = String(pkg.version)
  const files = SOURCE_DOCS.map((rel) => ({ rel, body: read(rel) }))
  const faq = files.find((f) => f.rel === 'docs/FAQ.md')
  const trouble = files.find((f) => f.rel === 'docs/troubleshooting.md')
  const questions = faq ? faqQuestions(faq.body) : []
  const symptoms = trouble ? symptomRows(trouble.body) : []

  const topicIndex = files
    .filter((f) => f.rel !== 'docs/llm-instructions.md')
    .map((f) => `- ${titleOf(f.body)} — source \`${f.rel}\``)
    .join('\n')

  const questionIndex = [
    ...symptoms.map((s) => `- Symptom: ${s} — see Troubleshooting`),
    ...questions.map((q) => `- ${q} — see FAQ`),
  ].join('\n')

  const parts = []
  parts.push(`# MyFileSync — AI support knowledge base

**Application:** MyFileSync  
**Version documented:** ${version}  
**Repository:** https://github.com/dobrado76/MyFileSync  
**Releases:** https://github.com/dobrado76/MyFileSync/releases/latest  
**Issues:** https://github.com/dobrado76/MyFileSync/issues  
**License:** GPL-3.0-only

This file is self-contained. You do not need the rest of the repository to answer ordinary questions about installing, configuring, comparing, syncing, or recovering from common failures.

Relative links inside source articles point at the repository tree (for example \`docs/BUILD.md\`). When this file is used alone, ignore those links and use the sections below. External https URLs remain valid.

Generated by \`npm run docs:build\`. Do not edit this file by hand.
`)

  parts.push(`## Topic index

${topicIndex}
`)

  parts.push(`## Question and symptom index

${questionIndex}
`)

  for (const file of files) {
    parts.push(`<!-- source: ${file.rel} -->\n\n${file.body.trim()}\n`)
  }

  return `${parts.join('\n')}\n`
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(root, 'AI-SUPPORT.md')
  fs.writeFileSync(out, buildAiSupport())
  console.log(`Wrote ${out}`)
}
